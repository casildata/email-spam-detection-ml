# Collects markdown sections while the scripts run; run_all.R writes them to docs/results.md.

.report <- new.env()
.report$sections <- character(0)

report_add <- function(...) {
  .report$sections <- c(.report$sections, paste0(..., collapse = ""))
}

# Percentages with a fixed number of decimals. Round with R first: the C library breaks
# exact ties differently on Windows and Linux, and accuracies are exact fractions.
pct <- function(x, digits = 2) formatC(round(100 * x, digits), format = "f", digits = digits)

md_table <- function(df) {
  fmt <- function(x) if (is.numeric(x)) format(x, big.mark = ",", trim = TRUE) else as.character(x)
  cells <- vapply(df, fmt, character(nrow(df)))
  if (is.null(dim(cells))) cells <- matrix(cells, nrow = 1)
  c(paste0("| ", paste(names(df), collapse = " | "), " |"),
    paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
    apply(cells, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |")))
}

report_write <- function(path) {
  header <- c("# Results",
              "",
              "Generated by `Rscript run_all.R` from UCI Spambase (see `data/README.md`).",
              "Percentages are on the validation set unless a row says otherwise.",
              "")
  writeLines(c(header, .report$sections), path)
}
